"""Async PostgreSQL metadata adapter with the same interface as the local test adapter."""
from __future__ import annotations

from contextlib import asynccontextmanager
import re
from typing import Any, Iterable, Sequence

import asyncpg
from app.config.settings import settings
from app.storage.schema import SCHEMA_STATEMENTS
from app.utils.logging import get_logger

log = get_logger("traceflow.postgres")


def pg_sql(sql: str) -> str:
    """Convert existing parameterized SQLite queries to asyncpg positional binds.

    SQL from this project never uses a question mark as a literal or SQL operator.
    """
    if sql.lstrip().upper().startswith("INSERT OR IGNORE INTO"):
        sql = re.sub(r"INSERT\s+OR\s+IGNORE\s+INTO", "INSERT INTO", sql, count=1, flags=re.I)
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    index = iter(range(1, sql.count("?") + 1))
    return re.sub(r"\?", lambda _: f"${next(index)}", sql)


class TransactionConnection:
    def __init__(self, conn: asyncpg.Connection):
        self.conn = conn

    async def execute(self, sql: str, params: Sequence[Any] = ()) -> str:
        return await self.conn.execute(pg_sql(sql), *params)

    async def executemany(self, sql: str, rows: Iterable[Sequence[Any]]) -> None:
        values = [tuple(row) for row in rows]
        if values:
            await self.conn.executemany(pg_sql(sql), values)


class Database:
    backend = "postgres"

    def __init__(self, url: str | None = None):
        self.url = url or settings.database_url
        if not self.url:
            raise ValueError("DATABASE_URL is required for PostgreSQL")
        self.pool: asyncpg.Pool | None = None
        self._healthy = False

    @property
    def healthy(self) -> bool:
        return self._healthy

    async def connect(self) -> None:
        # Render issues postgres:// URLs; asyncpg accepts both postgres:// and postgresql://.
        self.pool = await asyncpg.create_pool(dsn=self.url, min_size=1, max_size=5, command_timeout=30)
        async with self.pool.acquire() as conn:
            for statement in SCHEMA_STATEMENTS:
                sql = statement.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
                await conn.execute(sql)
        self._healthy = True
        log.info("postgres connected")

    async def close(self) -> None:
        if self.pool:
            await self.pool.close()
            self.pool = None
        self._healthy = False

    def _pool(self) -> asyncpg.Pool:
        if self.pool is None:
            raise RuntimeError("database is not connected")
        return self.pool

    async def execute(self, sql: str, params: Sequence[Any] = ()) -> int:
        async with self._pool().acquire() as conn:
            status = await conn.execute(pg_sql(sql), *params)
        return int(status.split()[-1]) if status.split()[-1].isdigit() else 0

    async def executemany(self, sql: str, rows: Iterable[Sequence[Any]]) -> int:
        items = [tuple(r) for r in rows]
        if items:
            async with self._pool().acquire() as conn:
                await conn.executemany(pg_sql(sql), items)
        return len(items)

    async def fetchall(self, sql: str, params: Sequence[Any] = ()) -> list[asyncpg.Record]:
        async with self._pool().acquire() as conn:
            return await conn.fetch(pg_sql(sql), *params)

    async def fetchone(self, sql: str, params: Sequence[Any] = ()) -> asyncpg.Record | None:
        async with self._pool().acquire() as conn:
            return await conn.fetchrow(pg_sql(sql), *params)

    async def scalar(self, sql: str, params: Sequence[Any] = ()) -> Any:
        async with self._pool().acquire() as conn:
            return await conn.fetchval(pg_sql(sql), *params)

    @asynccontextmanager
    async def transaction(self):
        async with self._pool().acquire() as conn:
            async with conn.transaction():
                yield TransactionConnection(conn)
